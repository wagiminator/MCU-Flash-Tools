# WCH-LinkW, WCH-LinkB, or compatible programmers/debuggers.
# Currently supports: CH32V002, CH32V003, CH32V004, CH32V005, CH32V006, CH32V007,
#                     CH32M007, CH32V103, CH32V203, CH32V205, CH32V208, CH32V303,
